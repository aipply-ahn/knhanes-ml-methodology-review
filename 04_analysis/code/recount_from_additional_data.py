def read_macros(numbers):
    mac = {}
    for f in ("legacy_numbers.tex", "oct_numbers.tex", "req_numbers.tex"):
        p = os.path.join(numbers, f)
        if os.path.exists(p):
            mac.update(re.findall(r"\\newcommand\{\\([a-zA-Z]+)\}\{(.*)\}\s*$", open(p, encoding="utf-8").read(), flags=re.M))
    if "kReqN" not in mac:   # author's tree: requirement numbers are generated by req_macros.py
        sys.path.insert(0, os.path.join(PROJECT, "rewrite/round4/03_manuscript_draft"))
        import req_macros
        mac.update(re.findall(r"\\newcommand\{\\([a-zA-Z]+)\}\{(.*)\}", req_macros.macros()))
    return mac


def sheet(path, name):
    rows = list(load_workbook(path, read_only=True)[name].iter_rows(values_only=True))
    h = [str(x) for x in rows[0]]
    return [{k: ("" if v is None else v) for k, v in zip(h, r)} for r in rows[1:]]


