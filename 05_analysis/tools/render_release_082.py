"""Render changed protocol/results pages and verify preserved figure-page evidence."""
from pathlib import Path
import json,hashlib,re,tarfile
import fitz
ROOT=Path(__file__).resolve().parents[1];REC=ROOT/'prompts/implementation_records/cycle_082';OUT=REC/'rendered'
OUT.mkdir(exist_ok=True)
assert not list(OUT.glob('*.png')), 'Use a new directory to preserve previous inspection evidence'
prior=ROOT/'project_archive/submission_versions/v081_20260924_102044'
manifest={r['path']:r['sha256'] for r in json.loads((prior/'manifest.json').read_text())['files']}
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
figures=[]
for p in sorted((ROOT/'figures/submission').rglob('*')):
 if p.is_file() and str(p.relative_to(ROOT)) in manifest:
  figures.append({'path':str(p.relative_to(ROOT)),'byte_identical':sha(p)==manifest[str(p.relative_to(ROOT))]})
main={str(p.relative_to(ROOT)):sha(p)==manifest[str(p.relative_to(ROOT))] for p in [ROOT/'manuscript/bmc_main.pdf',ROOT/'manuscript/bmc_main_ko.pdf']}
(REC/'figure_preservation.json').write_text(json.dumps({'verified_prior':str(prior.relative_to(ROOT)),'main_pdf_byte_identical':main,'figure_assets':figures,'prior_visual_evidence':'prompts/implementation_records/cycle_081/rendered/figure_inventory.json','scope':'Byte-identical PDFs retain the previous final-page visual inspection; changed supplement pages are rendered anew.'},indent=2)+'\n')
assert all(main.values()) and all(r['byte_identical'] for r in figures)
index={}
# Supplementary Figure S1 is regenerated by the table build; inspect its actual page too.
s1='manuscript/supplementary/pdf/Supplementary_Figure_S01_Full_health_topic_distribution.pdf'
s1doc=fitz.open(ROOT/s1)
s1doc[0].get_pixmap(matrix=fitz.Matrix(1.5,1.5)).save(OUT/'FigureS1_001.png')
with tarfile.open(prior/'snapshot.tar.gz') as archive:
    prior_s1=fitz.open(stream=archive.extractfile(s1).read(),filetype='pdf')
    same=prior_s1[0].get_pixmap(matrix=fitz.Matrix(1.5,1.5)).samples==s1doc[0].get_pixmap(matrix=fitz.Matrix(1.5,1.5)).samples
index['FigureS1']={'total_pages':len(s1doc),'rendered_pages':[1],'same_raster_as_v081':same}
for n in ['02','09']:
 p=next((ROOT/'manuscript/supplementary/pdf').glob('Supplementary_Table_S'+n+'_*.pdf'));doc=fitz.open(p)
 selected={1,2,len(doc),len(doc)-1}
 if n=='02':
  selected.add(len(doc)//2)
  for i,page in enumerate(doc):
   if any(t in page.get_text() for t in ['ELG02','OUT17','PRD14','SUR11','NC08','REP01']):selected.add(i+1)
 else:
  for i,page in enumerate(doc):
   if re.search(r'— [ABCD]\. ',page.get_text()):selected.update([i+1,min(len(doc),i+2)])
 for number in sorted(selected):doc[number-1].get_pixmap(matrix=fitz.Matrix(1.5,1.5)).save(OUT/f'S{n}_{number:03}.png')
 index['S'+n]={'total_pages':len(doc),'rendered_pages':sorted(selected)}
doc=fitz.open(ROOT/'manuscript/bmc_supplementary.pdf');selected={len(doc)}
for i,p in enumerate(doc):
 if 'Supplementary Table S2.' in p.get_text() or 'Supplementary Table S9.' in p.get_text():selected.update([i+1,min(len(doc),i+2)])
for number in sorted(selected):doc[number-1].get_pixmap(matrix=fitz.Matrix(1.3,1.3)).save(OUT/f'combined_{number:03}.png')
index['combined']={'total_pages':len(doc),'rendered_pages':sorted(selected)}
(OUT/'page_index.json').write_text(json.dumps(index,indent=2)+'\n');print(json.dumps(index,indent=2))
